// ----------------------------------------------------------------------------
// [1] 비동기 타이머 예시 (세탁기와 청소기 비유)
// ----------------------------------------------------------------------------
console.log("--- 1단계: 일상생활의 비동기 ---");
console.log("1. 세탁기에 빨래를 넣고 돌립니다. (비동기 작업 시작)");

// setTimeout은 대표적인 비동기 함수입니다.
// "3초(3000ms) 뒤에 이 함수(콜백)를 실행해 줘!" 라고 예약만 걸어두고, 
// 자바스크립트는 3초를 가만히 기다리지 않고 곧바로 다음 줄(22번 줄)로 쌩~ 지나갑니다.
setTimeout(() => {
    console.log("3. 👕 [알림] 띠리링~ 세탁이 모두 끝났습니다! (3초 경과)");
}, 3000);

// 세탁기가 돌아가는 동안 자바스크립트는 쉬지 않고 바로 다음 작업을 처리합니다.
// 덕분에 우리는 시간을 효율적으로 쓸 수 있죠!
console.log("2. 세탁기가 돌아가는 동안 거실 청소기를 돌립니다. (위이잉)");


// ----------------------------------------------------------------------------
// [2] 실전 서버 통신 예시 (fetch와 async/await)
// ----------------------------------------------------------------------------
// 조금 시간을 두고 서버 통신 예시를 보여주기 위해 다른 setTimeout으로 감쌌습니다.
setTimeout(() => {
    console.log("\n--- 2단계: 인터넷에서 데이터 가져오기 ---");

    // 데이터를 가져오는 비동기 함수를 선언합니다.
    async function loadUsers() {
        console.log("A. 서버에 유저 목록 데이터를 요청합니다... (해외 직구 주문 완료)");

        try {
            // await: "데이터가 올 때까지 여기서 잠깐 일시정지!" 
            // (주의: 함수 내부만 멈출 뿐, 프로그램 전체나 화면이 멈추는 것은 아닙니다)
            const response = await fetch('https://jsonplaceholder.typicode.com/users');
            
            // 데이터가 도착하면, 자바스크립트가 읽을 수 있게 포장을 뜯습니다(json 변환).
            // 이 포장을 뜯는 작업도 시간이 걸리므로 await를 써줍니다.
            const users = await response.json();

            // 모든 작업이 끝나면 결과를 출력합니다.
            console.log(`C. 📦 택배 도착! 총 ${users.length}명의 유저 데이터를 받았습니다.`);
            console.log(`D. 첫 번째 유저의 이름은 '${users[0].name}' 입니다.`);
            
        } catch (error) {
            // 인터넷이 끊기거나 주소가 잘못되었을 때 프로그램이 터지는 것을 막아줍니다.
            console.log("❌ 앗! 데이터를 가져오는 도중 문제가 발생했습니다.", error);
        }
    }

    // 위에서 만든 함수를 실제로 실행합니다.
    loadUsers();

    // ★ 가장 중요한 핵심 포인트 ★
    // loadUsers() 함수 안에서 데이터를 기다리고(await) 있는 동안, 
    // 자바스크립트 일꾼은 가만히 놀지 않고 이 함수 밖으로 빠져나와 아랫줄을 먼저 실행합니다!
    console.log("B. 서버에서 데이터를 가져오는 동안, 저는 화면에 다른 그림들을 그리고 있겠습니다!");

}, 4000); // 1단계 예시가 끝나고 4초 뒤에 실행되도록 설정