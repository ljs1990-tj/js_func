// ============================================================================
// 🌐 자바스크립트 실전 통신: Promise vs Async/Await (fetch API 활용)
// ============================================================================

// 우리가 데이터를 요청할 해외 쇼핑몰(가짜 유저 데이터 서버) 주소입니다.
const url = 'https://jsonplaceholder.typicode.com/users';

// ----------------------------------------------------------------------------
// [1] 전통적인 방식: Promise와 .then() 사용하기
// - 택배 배송: 송장 번호(Promise)를 받고, 단계별로 상자를 뜯는(.then) 과정입니다.
// ----------------------------------------------------------------------------
function fetchUsersWithPromise() {
    console.log("1. [Promise] 데이터 요청을 시작합니다... (택배 주문)");

    fetch(url)
        .then((response) => {
            // 첫 번째 .then(): 택배 상자가 무사히 도착했는지 확인합니다.
            console.log("2. [Promise] 응답 도착! 이제 포장을 뜯습니다(JSON 변환).");
            
            // 내용물을 자바스크립트가 읽을 수 있게 변환합니다. 
            // 이 작업도 시간이 걸리기 때문에 다음 .then()으로 결과를 넘겨줍니다.
            return response.json(); 
        })
        .then((users) => {
            // 두 번째 .then(): 포장을 다 뜯고 진짜 데이터(유저 목록)를 확인합니다.
            console.log(`3. [Promise] 변환 완료! 총 ${users.length}명의 유저가 있습니다.`);
            console.log(`   👉 첫 번째 유저 이름: ${users[0].name}\n`);
        })
        .catch((error) => {
            // 배송 중 인터넷이 끊기거나 주소가 틀렸을 때(에러) 여기서 한 번에 처리합니다.
            console.log("❌ [Promise] 데이터를 가져오는 중 에러가 발생했습니다:", error);
        });
}


// ----------------------------------------------------------------------------
// [2] 현대적인 방식: async / await 사용하기
// - 비동기 코드를 마치 위에서 아래로 흐르는 '일반적인 코드'처럼 아주 읽기 쉽게 만들어줍니다.
// ----------------------------------------------------------------------------

// 함수 앞에 async를 붙여서 "이 안에서 await(일시정지) 마법을 쓸 거야!" 라고 선언합니다.
async function fetchUsersWithAsyncAwait() {
    console.log("1. [Async/Await] 데이터 요청을 시작합니다... (택배 주문)");

    // 외부 인터넷 환경은 항상 변수가 많으므로(서버 다운 등), 무조건 try-catch로 감싸줍니다.
    try {
        // await: 데이터가 도착할 때까지 이 줄에서 잠시 기다립니다(일시정지).
        // (주의: 자바스크립트 일꾼 전체가 멈추는 게 아니라, 딱 이 함수 안에서만 기다립니다!)
        const response = await fetch(url);
        console.log("2. [Async/Await] 응답 도착! 이제 포장을 뜯습니다(JSON 변환).");

        // ★ 초보자 단골 실수 주의! ★
        // 데이터를 JSON으로 변환하는 작업도 비동기이므로 앞에 await를 꼭 붙여주어야 합니다.
        // 안 그러면 포장도 뜯기 전에 빈 상자를 열어보려다 에러가 납니다.
        const users = await response.json();

        // 변환까지 모두 끝나야 이 줄로 넘어옵니다. 코드가 훨씬 직관적이고 깔끔하죠?
        console.log(`3. [Async/Await] 변환 완료! 총 ${users.length}명의 유저가 있습니다.`);
        console.log(`   👉 첫 번째 유저 이름: ${users[0].name}\n`);

    } catch (error) {
        // try 안에서 문제가 생기면 프로그램이 터지지 않고 이쪽으로 넘어와서 에러를 안전하게 잡습니다.
        console.log("❌ [Async/Await] 에러 발생! 원인:", error);
    }
}


// ----------------------------------------------------------------------------
// 🚀 실행해보기
// ----------------------------------------------------------------------------
// 두 방식을 동시에 실행하면 콘솔 창에서 메시지 순서가 꼬일 수 있습니다.
// setTimeout을 이용해 Promise 방식이 먼저 실행되고, 대략 2초 뒤에 Async/Await 방식이 실행되도록 예약해 두었습니다.

console.log("--- Promise 방식 실행 ---");
fetchUsersWithPromise();

setTimeout(() => {
    console.log("--- Async/Await 방식 실행 ---");
    fetchUsersWithAsyncAwait();
}, 2000);