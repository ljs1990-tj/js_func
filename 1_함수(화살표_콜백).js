// ----------------------------------------------------------------------------
// 1. 콜백 함수 (Callback Function) 이해하기
// - 다른 함수에 '재료(인자)'로 전달되어서, 나중에 특정 상황이나 시간이 되면
//   "대신 실행해 줘!" 라고 맡겨두는 함수입니다. (카페의 진동벨 역할)
// ----------------------------------------------------------------------------

// 커피를 주문받는 함수를 하나 만들어 보겠습니다.
// 두 번째 매개변수인 'bell'이 바로 우리가 나중에 전달할 '콜백 함수(진동벨)'를 담을 바구니입니다.
function orderCoffee(coffeeName, bell) {
    console.log(`[주문 접수] ${coffeeName} 주문이 들어왔습니다.`);
    console.log("... 커피를 만드는 중입니다 (약 3초 소요) ...");

    // setTimeout은 자바스크립트에 내장된 대표적인 '콜백' 전용 함수입니다.
    // "특정 시간(여기선 3000ms = 3초)이 지난 후에, 첫 번째로 받은 함수를 실행해 줘!" 라는 뜻입니다.
    setTimeout(function() {
        console.log(`[제조 완료] ${coffeeName}가 다 만들어졌습니다!`);
        
        // ★ 핵심 포인트 ★
        // 커피 제조가 끝났으니, 주문할 때 받았던 진동벨(콜백 함수)을 마침내 울립니다.
        // 이때 함수 이름 뒤에 괄호()를 붙여야 실제로 코드가 실행이 됩니다.
        bell(); 
    }, 3000);
}

// 우리가 '진동벨'로 사용할 함수를 직접 하나 밖에서 만들어 봅니다.
function ringVibrationBell() {
    console.log("🔔 지잉- 지잉- (커피를 가지러 오세요!)");
}

// 이제 진짜로 커피를 주문해 봅시다.
// 🚨 [초보자 주의사항] 🚨
// 콜백 함수를 넘겨줄 때는 ringVibrationBell() 처럼 뒤에 괄호를 붙이면 절대 안 됩니다!
// 괄호를 붙이면 진동벨을 '건네주는' 게 아니라, 주문하자마자 그 자리에서 바로 '울려버리는' 대참사가 일어납니다.
// 반드시 함수 이름(함수 자체)만 살포시 넘겨주어야 합니다.
orderCoffee("아메리카노", ringVibrationBell);


// ----------------------------------------------------------------------------
// 2. 화살표 함수 (Arrow Function) 이해하기
// - 기존의 길고 거창한 함수 작성법(function)을 아주 짧고 간결하게 줄여 쓰는 최신 문법입니다.
// ----------------------------------------------------------------------------

// [일반적인 함수] - 격식을 차린 종이 편지 느낌
const addNormal = function(a, b) {
    return a + b;
};

// [화살표 함수: 1단계] - function 글자를 지우고, 매개변수 괄호 뒤에 화살표(=>)를 붙입니다.
const addArrow1 = (a, b) => {
    return a + b;
};

// [화살표 함수: 2단계 (실무에서 가장 많이 쓰는 형태!)]
// 만약 함수 안에 들어가는 코드가 '딱 한 줄'이고, 그 코드가 '결과값을 돌려주는(return)' 역할이라면?
// 코드를 감싸는 중괄호 { } 와 return 글자까지 전부 생략할 수 있습니다!
// 코드가 훨씬 깔끔해졌죠?
const addArrow2 = (a, b) => a + b; 

// [화살표 함수: 3단계 (매개변수가 1개일 때)]
// 들어오는 재료(매개변수)가 딱 1개라면, 매개변수를 감싸는 괄호 ( ) 마저도 생략 가능합니다.
const multiplyByTwo = x => x * 2;


// ----------------------------------------------------------------------------
// 3. 실전 응용: 콜백 함수 + 화살표 함수 합체!
// - 사실 자바스크립트에서는 콜백 함수를 바깥에 따로 예쁘게 만들어 두지 않습니다.
// - 다른 함수에게 콜백을 넘겨주는 그 자리에서, '화살표 함수'로 즉석에서 만들어 쓰는 경우가 99%입니다.
// ----------------------------------------------------------------------------

// 위에서 썼던 orderCoffee 함수를 다시 호출해 볼까요?
// 이번엔 바깥에 함수를 만들지 않고, 넘겨주는 자리에 화살표 함수를 직접 작성해서 바로 던져줍니다.

orderCoffee("카페라떼", () => {
    console.log("🔔 띠리링~ (라떼가 나왔네요, 즉석 화살표 함수로 만든 진동벨입니다!)");
});


// [또 다른 실전 예시: 배열의 forEach 메서드]
const fruits = ["사과", "바나나", "포도"];

console.log("--- 과일 목록 출력 ---");
// 배열 안의 요소들을 하나씩 순서대로 꺼내며 무언가 작업을 하고 싶을 때 forEach를 씁니다.
// fruits 배열이 자기 안의 과일을 하나씩 꺼내서, 우리가 넣어준 화살표 함수(콜백)의 재료(fruit)로 던져줍니다.
fruits.forEach((fruit) => {
    console.log(`맛있는 ${fruit} 🍎`);
});